#!/usr/bin/env node
/**
 * Assemble docs/ai-context/{help,setup-assistant,unified}.md from
 * docs/ai-context/source/* fragments (single source of truth).
 *
 * Usage:
 *   node desktop/scripts/sync-ai-context-packs.mjs          # write packs
 *   node desktop/scripts/sync-ai-context-packs.mjs --check  # fail on drift / stale facts
 *
 * Also asserts packs (and STUDY_SETUP_ASSISTANT.md) do not revive removed UI,
 * and that BuildWorkspace still mounts the labels the surface fragment claims.
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const repoRoot = path.resolve(__dirname, "../..");
const aiContextDir = path.join(repoRoot, "docs/ai-context");
const sourceDir = path.join(aiContextDir, "source");

const GENERATED_BANNER =
  "<!-- Generated by desktop/scripts/sync-ai-context-packs.mjs — edit docs/ai-context/source/ then re-run. -->\n";

/** Phrases that mean the docs drifted behind the mounted Study UI. */
const FORBIDDEN = [
  {
    re: /Help\s*→\s*Study assistant/i,
    why: "Study assistant opens from the menu bar Assistant toggle, not Help →",
  },
  {
    re: /Build\s*→\s*Setup assistant/i,
    why: "Build-page Setup assistant was removed; only the floating Study assistant remains",
  },
  {
    re: /Build panel \*\*Setup assistant\*\*/i,
    why: "No Build-panel Setup assistant is mounted",
  },
  {
    re: /There is no Apply button/i,
    why: "Apply appears when auto-commit is blocked; say auto-write + conflict Apply instead",
  },
  {
    // Title-case "Flop donk" was the old Build label. Allow lowercase
    // "flop donk" only in explicit absence wording elsewhere is still risky —
    // ban the historical control label form.
    re: /\bFlop donk\b/,
    why: "Old Build label «Flop donk» was removed; say turn/river donk only / no flop donk size control",
  },
  {
    re: /RangeCataloguePanel/i,
    why: "RangeCataloguePanel was replaced by SeatActionCatalogueTree",
  },
  {
    re: /Import JSON…/i,
    why: "Build catalogue is seat×action tree; do not advertise Import JSON on Build",
  },
  {
    re: /check-down equity/i,
    why: "Product copy calls it equity only; there is no other kind of equity in the UI",
  },
];

/** Must appear in assembled packs (product-accurate anchors). */
const REQUIRED_IN_PACKS = [
  { pack: "help.md", re: /menu bar \*\*Assistant\*\*/ },
  { pack: "help.md", re: /\*\*Equity\*\*/ },
  { pack: "help.md", re: /auto-write|writes those fields immediately|auto-commit/i },
  { pack: "setup-assistant.md", re: /no separate Build-page assistant/i },
  { pack: "setup-assistant.md", re: /Turn donk/ },
  { pack: "setup-assistant.md", re: /River donk/ },
  { pack: "setup-assistant.md", re: /no donk size control on the flop|flop has no donk/i },
  { pack: "unified.md", re: /contextSnapshot/ },
  { pack: "unified.md", re: /application receipt/i },
  { pack: "unified.md", re: /\*\*Equity\*\*/ },
  { pack: "unified.md", re: /Apply to Build/ },
  { pack: "unified.md", re: /list_bluff_candidates/ },
  { pack: "unified.md", re: /query_node_strategy/ },
  { pack: "unified.md", re: /query_selected_hand_analysis/ },
  { pack: "unified.md", re: /Compare runouts/ },
  { pack: "unified.md", re: /Overlay → EV\+Eq/ },
  { pack: "unified.md", re: /Global EV \(root-centered\)/ },
  { pack: "unified.md", re: /Q&A vs setup/ },
  { pack: "unified.md", re: /bluff candidates/i },
  { pack: "help.md", re: /Compare runouts/ },
  { pack: "help.md", re: /Overlay → EV\+Eq/ },
];

/** Labels that surface.md claims are mounted on Build — must exist in BuildWorkspace.tsx. */
const BUILD_LABELS_CLAIMED = [
  "Board",
  "Turn donk",
  "River donk",
  "Pot cap",
  "Merge threshold",
  "No 3-bet",
  "Iterations",
  "Accuracy",
  "Time limit",
  "Catalogue",
  "Open ranges in Equity",
];

function readSource(name) {
  const full = path.join(sourceDir, name);
  if (!fs.existsSync(full)) {
    throw new Error(`Missing source fragment: ${full}`);
  }
  return fs.readFileSync(full, "utf8").trim();
}

function assembleHelp(surface, helpBody) {
  return [
    GENERATED_BANNER.trimEnd(),
    "",
    "# Hold'em Study — product help section (for the AI)",
    "",
    "Use this section when answering **how-to / product** questions via `answer_user`.",
    "For the full unified role (Q&A + mutating setup), see `unified.md`.",
    "",
    helpBody,
    "",
    surface,
    "",
    "## Tone",
    "",
    "Be direct and accurate. If the player wants the app to change a study, call `emit_study_setup_proposal`. Conflict-free proposals auto-write; only conflicted proposals need **Apply to Build**. Do not tell them to click Apply after a normal write.",
    "",
  ].join("\n");
}

function assembleSetup(surface, setupRules) {
  return [
    GENERATED_BANNER.trimEnd(),
    "",
    "# Hold'em Study — setup mutation section (for the AI)",
    "",
    "Use this section when calling `emit_study_setup_proposal`.",
    "For the full unified role, see `unified.md`. The floating Study assistant (menu bar **Assistant**) uses these rules. There is **no separate Build-page assistant**.",
    "",
    "## Mission",
    "",
    "- Prepare / update / duplicate postflop studies from player wording.",
    "- Prefer exact catalogue ids over inventing frequencies.",
    "- Never emit scripts, shell commands, file paths, network URLs, or credentials.",
    "",
    setupRules,
    "",
    surface,
    "",
  ].join("\n");
}

